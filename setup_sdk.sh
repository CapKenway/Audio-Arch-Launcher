#!/usr/bin/env bash
set -euo pipefail

SDK_DIR="${1:-${HOME}/Android/Sdk}"
CMDLINE_TOOLS_URL="https://dl.google.com/android/repository/commandlinetools-linux-11076708_latest.zip"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "=== Setting up Android SDK for Audio Arch Launcher ==="
echo "Target SDK Directory: ${SDK_DIR}"

mkdir -p "${SDK_DIR}/cmdline-tools"

if [[ ! -x "${SDK_DIR}/cmdline-tools/latest/bin/sdkmanager" ]]; then
    echo "[*] Downloading official Android Command-Line Tools from Google..."
    TMP_ZIP="/tmp/cmdline-tools.zip"
    curl -L -o "${TMP_ZIP}" "${CMDLINE_TOOLS_URL}"
    
    echo "[*] Unpacking tools..."
    rm -rf "${SDK_DIR}/cmdline-tools/latest" "${SDK_DIR}/cmdline-tools/cmdline-tools"
    unzip -q "${TMP_ZIP}" -d "${SDK_DIR}/cmdline-tools"
    mv "${SDK_DIR}/cmdline-tools/cmdline-tools" "${SDK_DIR}/cmdline-tools/latest"
    rm -f "${TMP_ZIP}"
    echo "[✓] Command-line tools installed."
fi

export ANDROID_HOME="${SDK_DIR}"
export PATH="${SDK_DIR}/cmdline-tools/latest/bin:${SDK_DIR}/platform-tools:${PATH}"

echo "[*] Accepting licenses..."
yes | "${SDK_DIR}/cmdline-tools/latest/bin/sdkmanager" --licenses > /dev/null 2>&1 || true

echo "[*] Installing Android Platform 33 and Build-Tools..."
"${SDK_DIR}/cmdline-tools/latest/bin/sdkmanager" "platforms;android-33" "build-tools;33.0.2"

echo "[*] Creating local.properties in project..."
cat << EOF > "${PROJECT_DIR}/local.properties"
## Auto-generated by setup_sdk.sh
sdk.dir=${SDK_DIR}
EOF

echo "=== Android SDK setup complete! ==="
echo "You can now run:"
echo "  ./gradlew assembleDebug"

